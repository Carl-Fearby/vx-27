/** Seeded PRNG — stable across SSR/hydration. */
function createRng(seed = 0xca91fea7) {
  let state = seed >>> 0;
  return () => {
    state = (Math.imul(1664525, state) + 1013904223) >>> 0;
    return state / 0x100000000;
  };
}

function shuffleWith(rng, arr) {
  const out = arr.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/**
 * Round-robin interleave by first name so Carl/Clara/Cary blocks never clump.
 * (Plain shuffle still leaves long C-runs when ~28% of names share a prefix.)
 */
function mixNames(names, seed = 0xca91fea7) {
  const rng = createRng(seed);
  const buckets = new Map();

  for (const name of names) {
    const key = name.split(" ")[0];
    if (!buckets.has(key)) buckets.set(key, []);
    buckets.get(key).push(name);
  }

  const queues = shuffleWith(rng, [...buckets.keys()]).map((key) =>
    shuffleWith(rng, buckets.get(key))
  );

  const out = [];
  while (out.length < names.length) {
    for (const queue of queues) {
      if (queue.length) out.push(queue.shift());
    }
  }
  return out;
}

/** Production Staff wall — interleaved mix (no Carl/Carly runs). */
export const PRODUCTION_STAFF_SHUFFLED = Object.freeze(mixNames(PRODUCTION_STAFF));

/** Pick one name from the mixed roster (wraps). */
export function staffAt(index) {
  const len = PRODUCTION_STAFF_SHUFFLED.length;
  return PRODUCTION_STAFF_SHUFFLED[((index % len) + len) % len];
}

/** Pick three crew for a section (offset rotates who leads each department). */
export function trio(offset = 0) {
  return [0, 1, 2].map((i) => staffAt(offset + i));
}
